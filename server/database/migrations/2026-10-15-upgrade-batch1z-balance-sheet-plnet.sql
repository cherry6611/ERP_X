-- 修复 P0-1：资产负债表"未分配利润"在年终结转前漏计本期利润，导致月度中途恒等式不通过。
-- requires: 2026-10-15-upgrade-batch1-report-templates.sql
--
-- 背景：模板行 20 原公式 = 科目余额(410401, 贷) + 科目余额(4103, 贷)。
--   年终结转前 4103（本年利润）为空，本期净利润未进入权益 →
--   资产总计 ≠ 负债和所有者权益总计，差额恒等于本期净利润。
--
-- 修复：追加 本年损益净额()（= 本会计年度至本期末 损益类科目 收入 − 费用）。
--   年终结转后损益科目清零、4103 承接本期利润，该项为 0，不会与 4103 重复计算。
--
-- 说明：report-formula.ts 已支持 本年损益净额() 语法，ReportsService.ytdProfitLossNet()
--   在求值上下文注入该值。幂等：重复执行不改动已正确的公式。

UPDATE fin_report_template
SET formula = '科目余额(410401, 贷) + 科目余额(4103, 贷) + 本年损益净额()'
WHERE report_code = 'balance_sheet'
  AND row_no = '20'
  AND formula <> '科目余额(410401, 贷) + 科目余额(4103, 贷) + 本年损益净额()';
